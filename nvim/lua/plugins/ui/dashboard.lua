local function center(lines)
  local width = vim.o.columns
  local centered = {}
  for _, line in ipairs(lines) do
    local pad = math.max(0, math.floor((width - vim.fn.strdisplaywidth(line)) / 2))
    table.insert(centered, string.rep(' ', pad) .. line)
  end
  return centered
end

local function open()
  if vim.fn.argc() > 0 or vim.bo.filetype ~= '' or vim.bo.modified then return end

  local buf = vim.api.nvim_get_current_buf()
  if vim.api.nvim_buf_get_name(buf) ~= '' then return end

  local lines = vim.split(logo, '\n', { plain = true })
  while lines[1] == '' do
    table.remove(lines, 1)
  end
  while lines[#lines] == '' do
    table.remove(lines)
  end

  local height = vim.o.lines
  local top = math.max(0, math.floor((height - #lines) / 2) - 2)
  local content = {}
  for _ = 1, top do
    table.insert(content, '')
  end
  vim.list_extend(content, center(lines))
  table.insert(content, '')

  local has_session = session.exists()
  local hint = has_session and 'Existing session found open (s)' or 'press  \\  for files'
  table.insert(content, center({ hint })[1])

  vim.bo[buf].buftype = 'nofile'
  vim.bo[buf].bufhidden = 'wipe'
  vim.bo[buf].swapfile = false
  vim.bo[buf].modifiable = true
  vim.api.nvim_buf_set_lines(buf, 0, -1, false, content)
  vim.bo[buf].modifiable = false
  vim.bo[buf].modified = false
  vim.bo[buf].filetype = 'dashboard'
  vim.opt_local.number = false
  vim.opt_local.relativenumber = false
  vim.opt_local.signcolumn = 'no'
  vim.opt_local.foldcolumn = '0'
  vim.opt_local.cursorline = false
  vim.opt_local.list = false

end

vim.api.nvim_create_autocmd('VimEnter', {
  group = vim.api.nvim_create_augroup('dashboard', { clear = true }),
  callback = function() vim.schedule(open) end,
})
